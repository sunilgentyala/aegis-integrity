"""Deterministic citation-verification evaluation for AEGIS.

Runs the real AEGIS pipeline (document parsing + CitationIntegrityDetector)
on ``synthetic_paper.md``. Every HTTP request is answered from ``cases.json``
instead of the network, so the run is reproducible offline and never
contacts Crossref.

Usage (from the repository root):

    python benchmarks/citations/run_eval.py              # print the table
    python benchmarks/citations/run_eval.py --write      # also update results.md / results.json
    python benchmarks/citations/run_eval.py --html docs/demo/citation_demo_report.html

What this does NOT show: real-world accuracy. Twelve invented references
exercise specific code paths; they are not a sample of real bibliographies.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from unittest import mock

import requests

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
PAPER = HERE / "synthetic_paper.md"
CASES = HERE / "cases.json"

# Verdict -> what a human should conclude from it.
OUTCOME = {
    "VALID": "ok",
    "MISMATCH": "problem",
    "HALLUCINATED": "problem",
    "NOT_FOUND_IN_CROSSREF": "cannot_verify",
    "UNAVAILABLE": "cannot_verify",
    "UNRESOLVABLE": "cannot_verify",
    "NO_DOI": "cannot_verify",
}

MOCK_BANNER = (
    '<div style="background:#fff3cd;color:#664d03;border:2px solid #997404;'
    'padding:12px 16px;margin:0 0 16px;font:15px/1.4 system-ui,sans-serif">'
    "<b>Demonstration report.</b> Generated by AEGIS from "
    "<code>benchmarks/citations/synthetic_paper.md</code>, a synthetic paper whose "
    "authors, titles and DOIs are all invented. Crossref responses were "
    "<b>simulated</b> from <code>benchmarks/citations/cases.json</code>; no real "
    "lookups were made. Only the citation check was run.</div>"
)


class _Resp:
    def __init__(self, status: int, payload: dict | None = None):
        self.status_code = status
        self._payload = payload or {}

    def json(self):
        return self._payload


def _load_cases() -> list[dict]:
    return json.loads(CASES.read_text(encoding="utf-8"))["cases"]


def _fake_request_factory(cases: list[dict]):
    by_doi: dict[str, dict] = {}
    by_title: dict[str, dict] = {}
    for c in cases:
        if c.get("doi"):
            by_doi[c["doi"].lower()] = c
        if c.get("resolved_doi"):
            by_doi[c["resolved_doi"].lower()] = {"crossref": c["crossref_resolved"]}
        if "title_search" in c:
            by_title[str(c["ref"])] = c

    title_cases = sorted(by_title.values(), key=lambda c: c["ref"])

    def fake(self, method, url, **kwargs):
        base = "https://api.crossref.org/works"
        params = kwargs.get("params") or {}
        if url == base and "query.title" in params:
            q = params["query.title"].lower()
            for c in title_cases:
                items = c["title_search"]["items"]
                if items and items[0]["title"][0].lower()[:30] in q:
                    return _Resp(200, {"message": {"items": items}})
            return _Resp(200, {"message": {"items": []}})  # no Crossref match
        if not url.startswith(base + "/"):
            raise requests.ConnectionError(f"unexpected URL in evaluation: {url}")
        path = requests.utils.unquote(url[len(base) + 1:])
        want_agency = path.endswith("/agency")
        doi = path[: -len("/agency")] if want_agency else path
        case = by_doi.get(doi.lower())
        if case is None:
            return _Resp(404)
        spec = case.get("agency" if want_agency else "crossref", {"status": 404})
        if spec.get("timeout"):
            raise requests.Timeout("simulated timeout")
        return _Resp(spec["status"], {"message": spec.get("message", {})})

    return fake


def run(html_out: str | None = None) -> dict:
    sys.path.insert(0, str(ROOT))
    from aegis.core.pipeline import AEGISPipeline, PipelineConfig

    cases = _load_cases()
    cfg = PipelineConfig(
        run_ai_detector=False, run_semantic=False, run_stylometric=False,
        run_self_plagiarism=False, run_citation_network=False,
        run_venue_verification=False, run_watermark_detector=False,
        run_coherence_analyzer=False, run_math_check=False,
        run_grammar_check=False, run_ieee_plagiarism=False,
    )
    with mock.patch.object(requests.Session, "request", _fake_request_factory(cases)):
        pipeline = AEGISPipeline(config=cfg)
        # relative path keeps the generated report free of local folder names
        report = pipeline.analyze(str(PAPER.relative_to(ROOT)))

    verdicts = report.citation_verdicts
    rows = []
    for c, v in zip(cases, verdicts):
        outcome = OUTCOME.get(v.verdict, "cannot_verify")
        rows.append({
            "ref": c["ref"], "scenario": c["scenario"], "truth": c["truth"],
            "expected_verdict": c["expected_verdict"], "aegis_verdict": v.verdict,
            "aegis_outcome": outcome,
            "verdict_correct": v.verdict == c["expected_verdict"],
            "outcome_correct": outcome == c["truth"],
            "issues": v.issues,
        })

    problems = [r for r in rows if r["truth"] == "problem"]
    flagged = [r for r in rows if r["aegis_outcome"] == "problem"]
    tp = sum(1 for r in flagged if r["truth"] == "problem")
    false_fabrication = sum(
        1 for r in rows if r["aegis_verdict"] == "HALLUCINATED" and r["truth"] != "problem")
    unverifiable_called_problem = sum(
        1 for r in rows if r["truth"] == "cannot_verify" and r["aegis_outcome"] == "problem")
    summary = {
        "references": len(rows),
        "parsed_references": len(verdicts),
        "exact_verdict_matches": sum(r["verdict_correct"] for r in rows),
        "outcome_matches": sum(r["outcome_correct"] for r in rows),
        "problems_in_ground_truth": len(problems),
        "problems_flagged_correctly": tp,
        "flags_raised": len(flagged),
        "precision": round(tp / len(flagged), 3) if flagged else None,
        "recall": round(tp / len(problems), 3) if problems else None,
        "false_fabrication_claims": false_fabrication,
        "unverifiable_reported_as_problem": unverifiable_called_problem,
    }

    if html_out:
        from aegis.report.generator import ReportGenerator
        out = Path(html_out).resolve()
        out.parent.mkdir(parents=True, exist_ok=True)
        path = ReportGenerator(output_dir=str(out.parent)).generate_html(report, filename=out.name)
        html = Path(path).read_text(encoding="utf-8")
        marker = "<body>"
        if marker in html:
            html = html.replace(marker, marker + MOCK_BANNER, 1)
        else:
            html = MOCK_BANNER + html
        Path(path).write_text(html, encoding="utf-8")
        summary["html_report"] = str(out.relative_to(ROOT)) if out.is_relative_to(ROOT) else str(out)

    return {"summary": summary, "rows": rows}


def to_markdown(result: dict) -> str:
    s = result["summary"]
    lines = [
        "# Citation evaluation results",
        "",
        "Generated by `python benchmarks/citations/run_eval.py --write`. "
        "Synthetic data with simulated Crossref responses; see [README](README.md) "
        "for what these numbers do and do not mean.",
        "",
        f"- References in the paper: **{s['references']}** (parsed: {s['parsed_references']})",
        f"- Exact verdict matches: **{s['exact_verdict_matches']}/{s['references']}**",
        f"- Problems in ground truth: {s['problems_in_ground_truth']}; flagged correctly: "
        f"**{s['problems_flagged_correctly']}** (recall {s['recall']})",
        f"- Flags raised: {s['flags_raised']} (precision {s['precision']})",
        f"- Correct or unverifiable references labelled *fabricated*: "
        f"**{s['false_fabrication_claims']}**",
        f"- Unverifiable references reported as problems: "
        f"**{s['unverifiable_reported_as_problem']}**",
        "",
        "| # | Scenario | Truth | Expected | AEGIS | Match |",
        "|---|---|---|---|---|---|",
    ]
    for r in result["rows"]:
        mark = "yes" if r["verdict_correct"] else "**no (known miss)**"
        lines.append(f"| {r['ref']} | {r['scenario']} | {r['truth']} | "
                     f"{r['expected_verdict']} | {r['aegis_verdict']} | {mark} |")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write", action="store_true", help="update results.md and results.json")
    ap.add_argument("--html", default=None, help="also write an HTML demo report here")
    a = ap.parse_args()
    result = run(html_out=a.html)
    md = to_markdown(result)
    print(md)
    if a.write:
        (HERE / "results.md").write_text(md, encoding="utf-8")
        slim = {"summary": {k: v for k, v in result["summary"].items() if k != "html_report"},
                "rows": [{k: v for k, v in r.items() if k != "issues"} for r in result["rows"]]}
        (HERE / "results.json").write_text(json.dumps(slim, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
